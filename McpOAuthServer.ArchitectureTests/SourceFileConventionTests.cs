using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

using NUnit.Framework;

namespace McpOAuthServer.ArchitectureTests
{
    [TestFixture]
    public sealed class SourceFileConventionTests
    {
        [TestCase("McpOAuthServer")]
        [TestCase("McpOAuthServer.ArchitectureTests")]
        [TestCase("McpOAuthServer.IntegrationTests")]
        [TestCase("McpOAuthServer.UnitTests")]
        public void GivenHandwrittenSources_WhenCheckingSyntaxAndSemantics_ThenConventionsAreSatisfied(string projectName)
        {
            CSharpCompilation compilation = ArchitectureTestSources.Compilations[projectName];
            string[] violations = [.. compilation.SyntaxTrees.SelectMany(tree =>
                SourceConventionRules.Check(tree, compilation.GetSemanticModel(tree), projectName)
                    .Concat(SpecialisedConventionRules.Check(tree, compilation.GetSemanticModel(tree))))];

            Assert.That(violations, Is.Empty, string.Join(Environment.NewLine, violations));
        }

        [TestCase("McpOAuthServer")]
        [TestCase("McpOAuthServer.ArchitectureTests")]
        [TestCase("McpOAuthServer.IntegrationTests")]
        [TestCase("McpOAuthServer.UnitTests")]
        public void GivenAProject_WhenCheckingSourceFiles_ThenEachFileDefinesOneMatchingType(
            string projectName)
        {
            string projectDirectory = Path.Combine(ArchitectureTestSources.Root, projectName);

            Assert.That(
                File.Exists(Path.Combine(projectDirectory, $"{projectName}.csproj")),
                Is.True,
                $"The required project {projectName} must be available.");

            string[] sourceFiles = [.. ArchitectureTestSources.EnumerateFiles(projectDirectory)
                .OrderBy(filePath => filePath, StringComparer.Ordinal)];

            Assert.That(sourceFiles, Is.Not.Empty, $"{projectName} must contain handwritten C# sources.");

            string[] violations = [.. sourceFiles.SelectMany(filePath =>
                GetConventionViolations(filePath, File.ReadAllText(filePath)))];

            Assert.That(violations, Is.Empty, string.Join(Environment.NewLine, violations));
        }

        [TestCase("Registration.cs", "class Registration {}", 0)]
        [TestCase("Registration.cs", "interface Registration {}", 0)]
        [TestCase("Registration.cs", "enum Registration { Active }", 0)]
        [TestCase("Registration.cs", "delegate void Registration();", 0)]
        [TestCase("Registration.cs", "partial class Registration {}", 0)]
        [TestCase("Registration.cs", "", 1)]
        [TestCase("Program.cs", "System.Console.WriteLine();", 1)]
        [TestCase("Registration.cs", "class Registration {} class Another {}", 1)]
        [TestCase("Registration.cs", "class Registration { class Nested {} }", 1)]
        [TestCase("registration.cs", "class Registration {}", 1)]
        [TestCase("Another.cs", "class Registration {}", 1)]
        public void GivenSourceText_WhenCheckingConventions_ThenExpectedViolationsAreReported(
            string filePath,
            string source,
            int expectedViolationCount)
        {
            string[] violations = [.. GetConventionViolations(filePath, source)];

            using (Assert.EnterMultipleScope())
            {
                Assert.That(violations, Has.Length.EqualTo(expectedViolationCount));
                Assert.That(violations.All(violation => violation.Contains(filePath)), Is.True);
            }
        }

        [TestCase("Registration.cs", "class Registration {}", false)]
        [TestCase("Registration.g.cs", "class Registration {}", true)]
        [TestCase("Registration.generated.cs", "class Registration {}", true)]
        [TestCase("Registration.designer.cs", "class Registration {}", true)]
        [TestCase("Registration.cs", "// <auto-generated/>\nclass Registration {}", true)]
        public void GivenASourceFile_WhenCheckingGeneratedCode_ThenOnlyGeneratedFilesAreExcluded(
            string filePath,
            string source,
            bool isGenerated)
            => Assert.That(ArchitectureTestSources.IsGenerated(filePath, source), Is.EqualTo(isGenerated));

        private static IEnumerable<string> GetConventionViolations(
            string filePath,
            string source)
        {
            SyntaxNode root = CSharpSyntaxTree.ParseText(source).GetRoot();
            string[] typeNames = [.. root.DescendantNodes()
                .Where(node => node is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax)
                .Select(node => node switch
                {
                    BaseTypeDeclarationSyntax declaration => declaration.Identifier.ValueText,
                    DelegateDeclarationSyntax declaration => declaration.Identifier.ValueText,
                    _ => throw new InvalidOperationException("An unexpected type declaration was selected.")
                })];

            if (typeNames.Length != 1)
            {
                yield return $"{filePath}: Expected exactly one declared type, including nested types; found {typeNames.Length}.";
                yield break;
            }

            if (!string.Equals(Path.GetFileNameWithoutExtension(filePath), typeNames[0], StringComparison.Ordinal))
            {
                yield return $"{filePath}: The filename must match the declared type exactly: {typeNames[0]}.cs.";
            }
        }
    }
}